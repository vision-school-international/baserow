from django.conf import settings
from django.contrib.postgres.fields import ArrayField
from django.db import models

from baserow.contrib.database.fields.models import (
    Field,
    LongTextField,
    SingleSelectField,
)
from baserow.contrib.database.views.models import View
from baserow.core.formula.field import FormulaField as PromptFormulaField
from baserow.core.jobs.mixins import (
    JobWithUndoRedoIds,
    JobWithUserIpAddress,
    JobWithWebsocketId,
)
from baserow.core.jobs.models import Job


class AIPromptFieldMixin(models.Model):
    """
    The AI settings shared by both AI prompt field models. The cell itself is
    stored by the core parent model (long text or single select).
    """

    ai_generative_ai_type = models.CharField(max_length=32, null=True)
    ai_generative_ai_model = models.CharField(max_length=128, null=True)
    ai_temperature = models.FloatField(null=True)
    ai_prompt = PromptFormulaField(default="")
    ai_file_field = models.ForeignKey(
        Field,
        null=True,
        on_delete=models.SET_NULL,
        related_name="%(app_label)s_%(class)s_file_users",
    )
    ai_auto_update = models.BooleanField(default=False, db_default=False)
    ai_auto_update_user = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        null=True,
        on_delete=models.SET_NULL,
        related_name="+",
        help_text="The user on whose behalf the field is auto-updated.",
    )

    class Meta:
        abstract = True


class AIPromptTextField(AIPromptFieldMixin, LongTextField):
    pass


class AIPromptChoiceField(AIPromptFieldMixin, SingleSelectField):
    pass


AI_PROMPT_FIELD_MODELS = (AIPromptTextField, AIPromptChoiceField)


class AIPromptScheduledUpdate(models.Model):
    """A row waiting to be regenerated by an auto-updating field."""

    field = models.ForeignKey(Field, on_delete=models.CASCADE, related_name="+")
    row_id = models.PositiveIntegerField()
    updated_on = models.DateTimeField()

    class Meta:
        constraints = [
            models.UniqueConstraint(
                fields=["field", "row_id"], name="ai_tables_scheduled_field_row"
            )
        ]


class GenerateAIPromptValuesJob(JobWithUserIpAddress, Job):
    field = models.ForeignKey(
        Field,
        on_delete=models.CASCADE,
        related_name="+",
        help_text="The AI prompt field to generate values for.",
    )
    row_ids = ArrayField(
        models.IntegerField(),
        null=True,
        help_text="If set, only these rows are generated.",
    )
    view = models.ForeignKey(
        View,
        null=True,
        on_delete=models.CASCADE,
        related_name="+",
        help_text="If set (and no row ids), the rows visible in this view.",
    )
    only_empty = models.BooleanField(
        default=False, help_text="Only generate cells that are empty."
    )


class TransformAICellsJob(
    JobWithUserIpAddress, JobWithWebsocketId, JobWithUndoRedoIds, Job
):
    """
    Rewrites the selected cells of text fields in place with an instruction. The
    undo/redo ids let the rows update it makes be undone in the user's session,
    like DuplicateApplicationJob (core/models.py).
    """

    # TODO ZDM: remove this field in the next version
    field = models.ForeignKey(
        Field,
        null=True,
        on_delete=models.CASCADE,
        related_name="+",
        help_text="Deprecated, replaced by field_ids.",
    )
    field_ids = ArrayField(
        models.IntegerField(),
        null=True,
        help_text="The text fields of one table whose cells are rewritten.",
    )
    row_ids = ArrayField(
        models.IntegerField(), help_text="The rows whose cells are rewritten."
    )
    instruction = models.TextField(help_text="What the model does with every cell.")
    ai_generative_ai_type = models.CharField(max_length=32)
    ai_generative_ai_model = models.CharField(max_length=128)
    ai_temperature = models.FloatField(null=True)
    failed_row_ids = ArrayField(
        models.IntegerField(),
        default=list,
        help_text="The rows with a cell left unchanged: the model failed on it, or "
        "it was edited while the model ran.",
    )
